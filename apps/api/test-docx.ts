import htmlToDocx from 'html-to-docx';
import fs from 'fs';

async function test() {
  const htmlContent = `<div>
    <h1>UX Benchmark Report</h1>
    <p>Generated by UX Library</p>
    <h2>App: Test - Test</h2>
    <h3>UX Analysis</h3>
    <p>Test</p>
  </div>`;
  const buffer = await htmlToDocx(htmlContent, null, {
    title: 'UX Benchmark Report',
    margins: { top: 1440, right: 1440, bottom: 1440, left: 1440 }
  });
  
  fs.writeFileSync('test.docx', buffer);
  console.log('Saved to test.docx');
}

test();
