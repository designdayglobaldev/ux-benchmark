import { Document, Packer, Paragraph, TextRun, HeadingLevel, AlignmentType, Table, TableRow, TableCell, BorderStyle, WidthType, ImageRun } from 'docx';

export interface DocxExportParams {
  screens: any[];
  benchmarkData?: any;
}

export class ExportService {
  public static async generateDocxBuffer(params: DocxExportParams): Promise<Buffer> {
    const { screens, benchmarkData } = params;

    const stripHtmlKeepBold = (html: string | null | undefined): string[] => {
      if (!html) return ['No details provided.'];
      let text = html.replace(/<\/(p|div|li)>/gi, '\n').replace(/<br\s*\/?>/gi, '\n');
      text = text.replace(/<(?!strong\b|b\b|\/strong\b|\/b\b)[^>]*>/gi, '');
      text = text.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
      return text.split('\n').map(line => line.trim()).filter(line => line.length > 0);
    };

    const parseLine = (line: string): TextRun[] => {
      if (!line) return [];
      const parts = line.split(/(?:<strong>|<b>)(.*?)(?:<\/strong>|<\/b>)/gi);
      return parts.map((part, index) => {
        if (!part) return null;
        return new TextRun({ text: part, bold: index % 2 === 1 });
      }).filter((run): run is TextRun => run !== null);
    };

    const sections = [];

    // --- Title Page ---
    sections.push(
      new Paragraph({
        text: "UX Benchmark Analysis Report",
        heading: HeadingLevel.TITLE,
        alignment: AlignmentType.CENTER,
        spacing: { before: 2000, after: 400 },
      }),
      new Paragraph({
        text: "AI-Generated UX Insights",
        alignment: AlignmentType.CENTER,
        spacing: { after: 200 }
      }),
      new Paragraph({
        alignment: AlignmentType.CENTER,
        spacing: { after: 1000 },
        children: [new TextRun({ text: "Generated by UX Library", color: "888888", size: 28 })]
      }),
      new Paragraph({
        alignment: AlignmentType.CENTER,
        pageBreakBefore: false,
        children: [new TextRun({ text: new Date().toLocaleDateString(), color: "AAAAAA", size: 24 })]
      })
    );

    // --- AI Analysis Report ---
    if (benchmarkData) {
      sections.push(
        new Paragraph({
          text: "Executive Summary",
          heading: HeadingLevel.HEADING_1,
          pageBreakBefore: true,
        }),
        new Paragraph({
          children: parseLine(benchmarkData.overallAlignment || "No summary available."),
          spacing: { after: 400 },
        })
      );

      if (benchmarkData.snapshot) {
        sections.push(
          new Paragraph({
            text: "Snapshot",
            heading: HeadingLevel.HEADING_2,
            spacing: { before: 400, after: 200 }
          })
        );

        const snapshotRows: TableRow[] = [];
        const maxLen = Math.max(
          benchmarkData.snapshot.strongConventions?.length || 0,
          benchmarkData.snapshot.notableDifferences?.length || 0,
          benchmarkData.snapshot.keyOpportunities?.length || 0
        );

        snapshotRows.push(new TableRow({
          children: [
            new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: "Strong Conventions", bold: true })] })], shading: { fill: "F2F2F2" } }),
            new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: "Notable Differences", bold: true })] })], shading: { fill: "F2F2F2" } }),
            new TableCell({ children: [new Paragraph({ children: [new TextRun({ text: "Key Opportunities", bold: true })] })], shading: { fill: "F2F2F2" } }),
          ]
        }));

        for (let i = 0; i < maxLen; i++) {
          snapshotRows.push(new TableRow({
            children: [
              new TableCell({ children: [new Paragraph({ children: parseLine(benchmarkData.snapshot.strongConventions?.[i] || "-") })] }),
              new TableCell({ children: [new Paragraph({ children: parseLine(benchmarkData.snapshot.notableDifferences?.[i] || "-") })] }),
              new TableCell({ children: [new Paragraph({ children: parseLine(benchmarkData.snapshot.keyOpportunities?.[i] || "-") })] }),
            ]
          }));
        }

        sections.push(new Table({
          rows: snapshotRows,
          width: { size: 100, type: WidthType.PERCENTAGE }
        }));
      }

      if (benchmarkData.commonPatterns && benchmarkData.commonPatterns.length > 0) {
        sections.push(
          new Paragraph({
            text: "Common Benchmark Patterns",
            heading: HeadingLevel.HEADING_2,
            spacing: { before: 400, after: 200 }
          })
        );

        for (const pattern of benchmarkData.commonPatterns) {
          sections.push(
            new Paragraph({
              text: pattern.title,
              heading: HeadingLevel.HEADING_3,
              spacing: { before: 200, after: 100 }
            }),
            new Paragraph({
              children: [
                new TextRun({ text: "Evidence: ", bold: true }),
                ...parseLine(pattern.evidence || "N/A")
              ]
            }),
            new Paragraph({
              children: [
                new TextRun({ text: "Why It Matters: ", bold: true }),
                ...parseLine(pattern.whyItMatters || "N/A")
              ],
              spacing: { after: 200 }
            })
          );
        }
      }

      if (benchmarkData.designDifferences && benchmarkData.designDifferences.length > 0) {
        sections.push(
          new Paragraph({
            text: "Where Your Design Differs",
            heading: HeadingLevel.HEADING_2,
            spacing: { before: 400, after: 200 }
          })
        );

        for (const diff of benchmarkData.designDifferences) {
          sections.push(
            new Paragraph({
              text: diff.title,
              heading: HeadingLevel.HEADING_3,
              spacing: { before: 200, after: 100 }
            }),
            new Paragraph({
              children: [
                new TextRun({ text: "Your Design: ", bold: true }),
                ...parseLine(diff.yourDesign || "N/A")
              ]
            }),
            new Paragraph({
              children: [
                new TextRun({ text: "Benchmark Standard: ", bold: true }),
                ...parseLine(diff.benchmark || "N/A")
              ]
            }),
            new Paragraph({
              children: [
                new TextRun({ text: "Difference: ", bold: true }),
                ...parseLine(diff.difference || "N/A")
              ]
            }),
            new Paragraph({
              children: [
                new TextRun({ text: "Potential Impact: ", bold: true }),
                ...parseLine(diff.potentialImpact || "N/A")
              ],
              spacing: { after: 200 }
            })
          );
        }
      }

      if (benchmarkData.opportunities && benchmarkData.opportunities.length > 0) {
        sections.push(
          new Paragraph({
            text: "Actionable Opportunities",
            heading: HeadingLevel.HEADING_2,
            spacing: { before: 400, after: 200 }
          })
        );

        for (const opp of benchmarkData.opportunities) {
          sections.push(
            new Paragraph({
              text: opp.title,
              heading: HeadingLevel.HEADING_3,
              spacing: { before: 200, after: 100 }
            }),
            new Paragraph({
              children: [
                new TextRun({ text: "Observation: ", bold: true }),
                ...parseLine(opp.observation || "N/A")
              ]
            }),
            new Paragraph({
              children: [
                new TextRun({ text: "Recommendation: ", bold: true }),
                ...parseLine(opp.recommendation || "N/A")
              ],
              spacing: { after: 200 }
            })
          );
        }
      }
    }

    // --- Benchmark Competitor Screens Appendix (Visual Gallery) ---
    if (screens && screens.length > 0) {
      sections.push(
        new Paragraph({
          text: "Appendix: Benchmarked Screens",
          heading: HeadingLevel.HEADING_1,
          pageBreakBefore: true,
          spacing: { after: 200 }
        }),
        new Paragraph({
          text: "The following competitor screens were analyzed to benchmark your design against live market leaders.",
          spacing: { after: 400 }
        })
      );

      const imageCells: any[] = [];

      for (let i = 0; i < screens.length; i++) {
        const screen = screens[i];
        const appName = screen.app?.name || screen.name || `Competitor ${i + 1}`;
        
        let imgRun = null;
        if (screen.imageUrl) {
          try {
            if (screen.imageUrl.startsWith('data:image')) {
              // Base64 image
              const base64Data = screen.imageUrl.replace(/^data:image\/\w+;base64,/, '');
              const imgBuffer = Buffer.from(base64Data, 'base64');
              imgRun = new ImageRun({
                data: imgBuffer,
                transformation: {
                  width: 150,
                  height: 325,
                },
                type: screen.imageUrl.toLowerCase().includes('png') ? 'png' : 'jpg',
              });
            } else if (screen.imageUrl.startsWith('http://') || screen.imageUrl.startsWith('https://')) {
              // Remote URL fetch
              const imgRes = await fetch(screen.imageUrl);
              if (imgRes.ok) {
                const arrayBuffer = await imgRes.arrayBuffer();
                imgRun = new ImageRun({
                  data: Buffer.from(arrayBuffer),
                  transformation: {
                    width: 150,
                    height: 325,
                  },
                  type: screen.imageUrl.toLowerCase().match(/\.jpe?g$/) ? 'jpg' : 'png',
                });
              }
            }
          } catch (e) {
            console.error("Failed to fetch image for docx:", e);
          }
        }

        imageCells.push(
          new TableCell({
            borders: {
              top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
              bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
              left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
              right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            },
            children: [
              new Paragraph({
                children: [new TextRun({ text: appName, bold: true })],
                alignment: AlignmentType.CENTER,
                spacing: { after: 100 }
              }),
              new Paragraph({
                alignment: AlignmentType.CENTER,
                children: imgRun ? [imgRun] : [new TextRun("Image not available")],
              })
            ],
          })
        );
      }

      // Group cells into rows of 3 columns
      const tableRows: TableRow[] = [];
      for (let i = 0; i < imageCells.length; i += 3) {
        const rowCells = imageCells.slice(i, i + 3);
        while (rowCells.length < 3) {
          rowCells.push(new TableCell({
            borders: {
              top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
              bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
              left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
              right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            },
            children: [new Paragraph("")]
          }));
        }
        tableRows.push(new TableRow({ children: rowCells }));
      }

      if (tableRows.length > 0) {
        sections.push(
          new Table({
            rows: tableRows,
            width: { size: 100, type: WidthType.PERCENTAGE },
            borders: {
              top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
              bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
              left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
              right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
              insideHorizontal: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
              insideVertical: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            }
          })
        );
      }

      // --- Screen Details Breakdown ---
      for (let i = 0; i < screens.length; i++) {
        const screen = screens[i];
        if (screen.uxAnalysis) {
          sections.push(
            new Paragraph({
              text: `${i + 1}. ${screen.name || 'Screen'} UX Breakdown`,
              heading: HeadingLevel.HEADING_2,
              spacing: { before: 300, after: 100 }
            })
          );
          const lines = stripHtmlKeepBold(screen.uxAnalysis);
          for (const line of lines) {
            sections.push(new Paragraph({ children: parseLine(line), spacing: { after: 100 } }));
          }
        }
      }
    }

    const doc = new Document({
      styles: {
        paragraphStyles: [
          {
            id: "Normal",
            name: "Normal",
            run: {
              size: 22,
              color: "2A2A2A",
              font: "Helvetica",
            },
            paragraph: {
              spacing: { line: 276, after: 140 },
            },
          },
          {
            id: "Title",
            name: "Title",
            basedOn: "Normal",
            next: "Normal",
            run: {
              size: 56,
              bold: true,
              color: "111111",
              font: "Helvetica",
            },
          },
          {
            id: "Heading1",
            name: "Heading 1",
            basedOn: "Normal",
            next: "Normal",
            quickFormat: true,
            run: {
              size: 36,
              bold: true,
              color: "0052CC",
            },
            paragraph: {
              spacing: { before: 400, after: 200 },
            },
          },
          {
            id: "Heading2",
            name: "Heading 2",
            basedOn: "Normal",
            next: "Normal",
            quickFormat: true,
            run: {
              size: 28,
              bold: true,
              color: "1A1A1A",
            },
            paragraph: {
              spacing: { before: 300, after: 120 },
            },
          },
        ]
      },
      sections: [
        {
          properties: {},
          children: sections,
        },
      ],
    });

    const b64string = await Packer.toBase64String(doc);
    return Buffer.from(b64string, 'base64');
  }
}

