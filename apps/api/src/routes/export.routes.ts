import { Router, Request, Response } from 'express';
import { Document, Packer, Paragraph, TextRun, HeadingLevel, ImageRun, AlignmentType, Table, TableRow, TableCell, BorderStyle, WidthType } from 'docx';

const router = Router();

router.post('/docx', async (req: Request, res: Response): Promise<any> => {
  try {
    const { screens, benchmarkData } = req.body;

    if (!screens || !Array.isArray(screens)) {
      return res.status(400).json({ error: 'Screens data is required.' });
    }

    const stripHtmlKeepBold = (html: string | null | undefined): string[] => {
      if (!html) return ['No details provided.'];
      let text = html.replace(/<\/(p|div|li)>/gi, '\n').replace(/<br\s*\/?>/gi, '\n');
      text = text.replace(/<(?!strong\b|b\b|\/strong\b|\/b\b)[^>]*>/gi, '');
      text = text.replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>');
      return text.split('\n').map(line => line.trim()).filter(line => line.length > 0);
    };

    const parseLine = (line: string): TextRun[] => {
      if (!line) return [];
      const parts = line.split(/(?:<strong>|<b>)(.*?)(?:<\/strong>|<\/b>)/gi);
      return parts.map((part, index) => {
        if (!part) return null;
        return new TextRun({ text: part, bold: index % 2 === 1 });
      }).filter((run): run is TextRun => run !== null);
    };

    const sections = [];

    // --- Title Page ---
    sections.push(
      new Paragraph({
        text: "UX Benchmark Analysis Report",
        heading: HeadingLevel.TITLE,
        alignment: AlignmentType.CENTER,
        spacing: { before: 2000, after: 400 },
      }),
      new Paragraph({
        text: "AI-Generated UX Insights",
        alignment: AlignmentType.CENTER,
        spacing: { after: 200 }
      }),
      new Paragraph({
        alignment: AlignmentType.CENTER,
        spacing: { after: 1000 },
        children: [new TextRun({ text: "Generated by UX Library", color: "888888", size: 28 })]
      }),
      new Paragraph({
        alignment: AlignmentType.CENTER,
        pageBreakBefore: false,
        children: [new TextRun({ text: new Date().toLocaleDateString(), color: "AAAAAA", size: 24 })]
      })
    );

    // --- AI Analysis Report ---
    if (benchmarkData) {
      sections.push(
        new Paragraph({
          text: "Executive Summary",
          heading: HeadingLevel.HEADING_1,
          pageBreakBefore: true,
        }),
        new Paragraph({
          children: parseLine(benchmarkData.overallAlignment || "No summary available."),
          spacing: { after: 400 },
        })
      );

      if (benchmarkData.snapshot) {
        sections.push(
          new Paragraph({
            text: "Snapshot",
            heading: HeadingLevel.HEADING_2,
            spacing: { before: 400, after: 200 }
          })
        );

        if (benchmarkData.snapshot.strongConventions?.length) {
          sections.push(new Paragraph({ text: "Strong Conventions Followed", heading: HeadingLevel.HEADING_3 }));
          benchmarkData.snapshot.strongConventions.forEach((item: string) => {
            sections.push(new Paragraph({ children: parseLine(item), bullet: { level: 0 } }));
          });
        }

        if (benchmarkData.snapshot.notableDifferences?.length) {
          sections.push(new Paragraph({ text: "Notable Differences", heading: HeadingLevel.HEADING_3, spacing: { before: 200 } }));
          benchmarkData.snapshot.notableDifferences.forEach((item: string) => {
            sections.push(new Paragraph({ children: parseLine(item), bullet: { level: 0 } }));
          });
        }

        if (benchmarkData.snapshot.keyOpportunities?.length) {
          sections.push(new Paragraph({ text: "Key Opportunities", heading: HeadingLevel.HEADING_3, spacing: { before: 200 } }));
          benchmarkData.snapshot.keyOpportunities.forEach((item: string) => {
            sections.push(new Paragraph({ children: parseLine(item), bullet: { level: 0 } }));
          });
        }
      }

      if (benchmarkData.commonPatterns?.length) {
        sections.push(new Paragraph({ text: "Common Patterns in Industry", heading: HeadingLevel.HEADING_2, spacing: { before: 400, after: 200 } }));
        benchmarkData.commonPatterns.forEach((pattern: any) => {
          sections.push(new Paragraph({ text: pattern.title || "Pattern", heading: HeadingLevel.HEADING_3 }));
          if (pattern.evidence) {
             sections.push(new Paragraph({ children: [new TextRun({ text: "Evidence: ", bold: true }), ...parseLine(pattern.evidence)] }));
          }
          if (pattern.whyItMatters) {
             sections.push(new Paragraph({ children: [new TextRun({ text: "Why it matters: ", bold: true }), ...parseLine(pattern.whyItMatters)], spacing: { after: 200 } }));
          }
        });
      }

      if (benchmarkData.designDifferences?.length) {
        sections.push(new Paragraph({ text: "Design Differences", heading: HeadingLevel.HEADING_2, spacing: { before: 400, after: 200 } }));
        benchmarkData.designDifferences.forEach((diff: any) => {
          sections.push(new Paragraph({ text: diff.title || "Difference", heading: HeadingLevel.HEADING_3 }));
          if (diff.yourDesign) sections.push(new Paragraph({ children: [new TextRun({ text: "Your design: ", bold: true }), ...parseLine(diff.yourDesign)] }));
          if (diff.benchmark) sections.push(new Paragraph({ children: [new TextRun({ text: "Benchmark: ", bold: true }), ...parseLine(diff.benchmark)] }));
          if (diff.difference) sections.push(new Paragraph({ children: [new TextRun({ text: "Difference: ", bold: true }), ...parseLine(diff.difference)] }));
          if (diff.potentialImpact) sections.push(new Paragraph({ children: [new TextRun({ text: "Impact: ", bold: true }), ...parseLine(diff.potentialImpact)], spacing: { after: 200 } }));
        });
      }

      if (benchmarkData.opportunities?.length) {
        sections.push(new Paragraph({ text: "Opportunities for Improvement", heading: HeadingLevel.HEADING_2, spacing: { before: 400, after: 200 } }));
        benchmarkData.opportunities.forEach((opp: any) => {
          sections.push(new Paragraph({ text: opp.title || "Opportunity", heading: HeadingLevel.HEADING_3 }));
          if (opp.observation) sections.push(new Paragraph({ children: [new TextRun({ text: "Observation: ", bold: true }), ...parseLine(opp.observation)] }));
          if (opp.recommendation) sections.push(new Paragraph({ children: [new TextRun({ text: "Recommendation: ", bold: true }), ...parseLine(opp.recommendation)] }));
          if (opp.evidence) sections.push(new Paragraph({ children: [new TextRun({ text: "Evidence: ", bold: true }), ...parseLine(opp.evidence)] }));
          if (opp.confidence) sections.push(new Paragraph({ children: [new TextRun({ text: "Confidence: ", bold: true }), ...parseLine(opp.confidence)], spacing: { after: 200 } }));
        });
      }
    }

    // --- Benchmarked Screens Appendix (Gallery) ---
    sections.push(
      new Paragraph({
        text: "Appendix: Benchmarked Screens",
        heading: HeadingLevel.HEADING_1,
        pageBreakBefore: true,
      }),
      new Paragraph({
        text: "The following competitor screens were used by the AI to benchmark your design and generate this report.",
        spacing: { after: 400 }
      })
    );

    const imageCells: any[] = [];

    for (let i = 0; i < screens.length; i++) {
      const screen = screens[i];
      const appName = screen.app?.name || 'Competitor';
      
      let imgRun = null;
      if (screen.imageUrl) {
        try {
          const imgRes = await fetch(screen.imageUrl);
          if (imgRes.ok) {
            const arrayBuffer = await imgRes.arrayBuffer();
            imgRun = new ImageRun({
              data: Buffer.from(arrayBuffer),
              transformation: {
                width: 150,
                height: 325, 
              },
              type: screen.imageUrl.toLowerCase().match(/\.jpe?g$/) ? "jpg" : "png",
            });
          }
        } catch (e) {
          console.error("Failed to fetch image for docx:", e);
        }
      }

      imageCells.push(
        new TableCell({
          borders: {
            top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
          },
          children: [
            new Paragraph({ children: [new TextRun({ text: appName, bold: true })], alignment: AlignmentType.CENTER, spacing: { after: 100 } }),
            new Paragraph({
              alignment: AlignmentType.CENTER,
              children: imgRun ? [imgRun] : [new TextRun("Image not available")],
            })
          ],
        })
      );
    }

    // Group cells into rows of 3 columns
    const tableRows = [];
    for (let i = 0; i < imageCells.length; i += 3) {
      const rowCells = imageCells.slice(i, i + 3);
      // Pad row to 3 cells if needed
      while (rowCells.length < 3) {
        rowCells.push(new TableCell({ 
          borders: {
            top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
          },
          children: [new Paragraph("")] 
        }));
      }
      tableRows.push(new TableRow({ children: rowCells }));
    }

    if (tableRows.length > 0) {
      sections.push(
        new Table({
          rows: tableRows,
          width: { size: 100, type: WidthType.PERCENTAGE },
          borders: {
            top: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            bottom: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            left: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            right: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            insideHorizontal: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
            insideVertical: { style: BorderStyle.NONE, size: 0, color: "FFFFFF" },
          }
        })
      );
    }

    const doc = new Document({
      styles: {
        default: {
          document: {
            run: {
              size: 22, // 11pt
              font: "Helvetica",
              color: "333333",
            },
            paragraph: {
              spacing: { line: 276, before: 100, after: 100 },
            },
          },
        },
        paragraphStyles: [
          {
            id: "Title",
            name: "Title",
            basedOn: "Normal",
            next: "Normal",
            run: {
              size: 56, // 28pt
              bold: true,
              color: "111111",
              font: "Helvetica",
            },
          },
          {
            id: "Heading1",
            name: "Heading 1",
            basedOn: "Normal",
            next: "Normal",
            quickFormat: true,
            run: {
              size: 36, // 18pt
              bold: true,
              color: "0052CC", // Professional Blue
            },
            paragraph: {
              spacing: { before: 400, after: 200 },
            },
          },
          {
            id: "Heading2",
            name: "Heading 2",
            basedOn: "Normal",
            next: "Normal",
            quickFormat: true,
            run: {
              size: 28, // 14pt
              bold: true,
              color: "1A1A1A",
            },
            paragraph: {
              spacing: { before: 300, after: 120 },
            },
          },
          {
            id: "Heading3",
            name: "Heading 3",
            basedOn: "Normal",
            next: "Normal",
            quickFormat: true,
            run: {
              size: 24, // 12pt
              bold: true,
              color: "444444",
            },
            paragraph: {
              spacing: { before: 200, after: 100 },
            },
          },
        ]
      },
      sections: [
        {
          properties: {},
          children: sections,
        },
      ],
    });

    const b64string = await Packer.toBase64String(doc);
    const buffer = Buffer.from(b64string, 'base64');

    res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.wordprocessingml.document');
    res.setHeader('Content-Disposition', 'attachment; filename="UX-Benchmark-Report.docx"');
    res.setHeader('Content-Length', buffer.length.toString());
    res.send(buffer);

  } catch (error: any) {
    console.error('Error generating DOCX:', error);
    res.status(500).json({ error: error.message, stack: error.stack });
  }
});

export default router;
